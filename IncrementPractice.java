public class IncrementPractice {
	public static void main (String []args) {
		
		//1. Post Increment
		
		int a = 10;
		int b = 9;
		int c = a+++ b ;
		System.out.println("Post-increment\n c = "+c);

         //2. Pre Increment
		 
		int a = 10;
		int b = 9;
		int c = ++a + b;
		System.out.println("Pre-Increment\n c = "+c);

       }//end of main method
 
 }//end of class
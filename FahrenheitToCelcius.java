public class FarenheightToCelcius{

  public static void main ( String[] args) {
  
         //input = assign
				  
				  int farenheight = 56;
				  float celius = 0F;
				  
				  
				  //statement
				  System.out.println("Farenheight To Celcius");
				  
				  //process (38 F - 32) x 5/9 = 3.333C
				  celcius = (farenheight-32) * 5F/9F;
				  
				  //output
				  System.out.println("Farenheight To Celcius: \t" + celcius);
				  
				  
				  
				  
				  
				  
				  
				  
				 
          }//end of main method
  
}//end of class
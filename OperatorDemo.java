public class OperatorDemo {
public static void main(String args []) {
	  
	  //data type ... variables
	  int x = 30;
	  int y = 10;
	  int z = 20;
      
	  
	  System.out.println(x + "+" + y + "=" + (x + y) );
	  System.out.println(x + "-" + y + "=" + (x - y) );
	  System.out.println(z + "*" + x + "=" + (z * x) );
	  System.out.println(y + "/" + z + "=" + (y / z) );
	  System.out.println(x + "%" + z + "=" + (x % z) );
	  
  }//end of main method
}//end of class
	  